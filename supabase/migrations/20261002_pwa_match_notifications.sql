-- Store anonymous web-push endpoints server-side. The table is only read and
-- written by the service-role API; browser clients never receive its keys.
CREATE TABLE IF NOT EXISTS public_push_subscriptions (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  endpoint TEXT NOT NULL UNIQUE,
  p256dh TEXT NOT NULL,
  auth TEXT NOT NULL,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
  updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

ALTER TABLE public_push_subscriptions ENABLE ROW LEVEL SECURITY;
REVOKE ALL ON public_push_subscriptions FROM anon, authenticated;
GRANT ALL ON public_push_subscriptions TO service_role;
GRANT USAGE, SELECT ON SEQUENCE public_push_subscriptions_id_seq TO service_role;

ALTER TABLE fixtures
